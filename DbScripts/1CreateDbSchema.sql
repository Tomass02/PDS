-- Zakladna schema veterinarnej ambulancie.

-- Definuje zlozeny objektovy typ adresy pouzivany pri majitelovi.
CREATE OR REPLACE TYPE t_adresa AS OBJECT (
    ulica VARCHAR2(100),
    mesto VARCHAR2(100),
    psc   VARCHAR2(20),
    stat  VARCHAR2(50)
);
/

-- Definuje objektovy typ so zdravotnymi udajmi a jeho verejnymi metodami.
CREATE OR REPLACE TYPE t_zdravotny_stav AS OBJECT (
    teplota_c   NUMBER(4,1),
    srdecn_tep  NUMBER(3),
    hmotnost_kg NUMBER(5,2),
    zavaznost   VARCHAR2(50),
    CONSTRUCTOR FUNCTION t_zdravotny_stav (
        p_teplota_c   NUMBER,
        p_srdecn_tep  NUMBER,
        p_hmotnost_kg NUMBER,
        p_zavaznost   VARCHAR2
    ) RETURN SELF AS RESULT,
    MEMBER FUNCTION vypocitaj_rizikovy_index RETURN NUMBER,
    MEMBER FUNCTION to_json_string RETURN CLOB,
    MAP MEMBER FUNCTION sort_key RETURN NUMBER
);
/

-- Implementuje konstruktor a metody objektoveho typu.
CREATE OR REPLACE TYPE BODY t_zdravotny_stav AS
    -- Inicializuje vsetky atributy noveho zdravotneho stavu.
    CONSTRUCTOR FUNCTION t_zdravotny_stav (
        p_teplota_c   NUMBER,
        p_srdecn_tep  NUMBER,
        p_hmotnost_kg NUMBER,
        p_zavaznost   VARCHAR2
    ) RETURN SELF AS RESULT IS
    BEGIN
        SELF.teplota_c := p_teplota_c;
        SELF.srdecn_tep := p_srdecn_tep;
        SELF.hmotnost_kg := p_hmotnost_kg;
        SELF.zavaznost := p_zavaznost;
        RETURN;
    END;

    -- vypocet rizikoveho indexu.
    MEMBER FUNCTION vypocitaj_rizikovy_index RETURN NUMBER IS
    BEGIN
        RETURN NULL;
    END;

    -- prevodu stavu na JSON.
    MEMBER FUNCTION to_json_string RETURN CLOB IS
    BEGIN
        RETURN NULL;
    END;

    -- kluc na porovnavanie objektov.
    MAP MEMBER FUNCTION sort_key RETURN NUMBER IS
    BEGIN
        RETURN NULL;
    END;
END;
/

-- Uklada spolocne osobne udaje majitelov a veterinarov.
CREATE TABLE osoba (
    id_osoba   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    meno       VARCHAR2(50) NOT NULL,
    priezvisko VARCHAR2(50) NOT NULL,
    telefon    VARCHAR2(25),
    email      VARCHAR2(100),
    CONSTRAINT osoba_pk PRIMARY KEY (id_osoba)
);

-- Eviduje rolu majitela, jeho adresu a jedinecny odkaz na osobu.
CREATE TABLE majitel (
    id_majitel NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_osoba   NUMBER NOT NULL,
    adresa     t_adresa NOT NULL,
    CONSTRAINT majitel_pk PRIMARY KEY (id_majitel),
    CONSTRAINT majitel_osoba_fk FOREIGN KEY (id_osoba)
        REFERENCES osoba (id_osoba),
    CONSTRAINT majitel_osoba_uq UNIQUE (id_osoba)
);

-- Eviduje rolu veterinara a jedinecny odkaz na osobu.
CREATE TABLE veterinar (
    id_veterinar  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_osoba      NUMBER NOT NULL,
    specializacia VARCHAR2(100) NOT NULL,
    CONSTRAINT veterinar_pk PRIMARY KEY (id_veterinar),
    CONSTRAINT veterinar_osoba_fk FOREIGN KEY (id_osoba)
        REFERENCES osoba (id_osoba),
    CONSTRAINT veterinar_osoba_uq UNIQUE (id_osoba)
);

-- Uklada zvierata a ich vlastnika.
CREATE TABLE zviera (
    id_zviera       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_majitel      NUMBER NOT NULL,
    meno            VARCHAR2(50) NOT NULL,
    druh            VARCHAR2(50) NOT NULL,
    datum_narodenia DATE NOT NULL,
    plemeno         VARCHAR2(50),
    fotografia      BLOB,
    CONSTRAINT zviera_pk PRIMARY KEY (id_zviera),
    CONSTRAINT zviera_majitel_fk FOREIGN KEY (id_majitel)
        REFERENCES majitel (id_majitel)
);

-- Uklada zdravotnu kartu; 
-- UNIQUE zabranuje viac kartam pre jedno zviera.
CREATE TABLE zdravotna_karta (
    id_zdravotna_karta NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_zviera          NUMBER NOT NULL,
    datum_zalozenia    DATE NOT NULL,
    poznamka           VARCHAR2(200),
    CONSTRAINT zdravotna_karta_pk PRIMARY KEY (id_zdravotna_karta),
    CONSTRAINT zdravotna_karta_zviera_fk FOREIGN KEY (id_zviera)
        REFERENCES zviera (id_zviera),
    CONSTRAINT zdravotna_karta_zviera_uq UNIQUE (id_zviera)
);

-- Uklada vysetrenia, ich zdravotny stav a vykonavajuceho veterinara.
CREATE TABLE vysetrenie (
    id_vysetrenie        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_zdravotna_karta   NUMBER NOT NULL,
    id_veterinar         NUMBER NOT NULL,
    datum_cas_vysetrenia TIMESTAMP NOT NULL,
    diagnoza             VARCHAR2(500),
    popis_liecby         VARCHAR2(500),
    detaily_stavu        t_zdravotny_stav NOT NULL,
    CONSTRAINT vysetrenie_pk PRIMARY KEY (id_vysetrenie),
    CONSTRAINT vysetrenie_karta_fk FOREIGN KEY (id_zdravotna_karta)
        REFERENCES zdravotna_karta (id_zdravotna_karta),
    CONSTRAINT vysetrenie_veterinar_fk FOREIGN KEY (id_veterinar)
        REFERENCES veterinar (id_veterinar)
);

-- Uklada najviac jednu fakturu ku konkretnemu vysetreniu.
CREATE TABLE faktura (
    id_faktura       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_vysetrenie    NUMBER NOT NULL,
    suma_celkom      NUMBER(10,2) NOT NULL,
    datum_vystavenia DATE NOT NULL,
    datum_splatnosti DATE NOT NULL,
    stav_uhrady      VARCHAR2(20),
    scan_faktury     BLOB,
    CONSTRAINT faktura_pk PRIMARY KEY (id_faktura),
    CONSTRAINT faktura_vysetrenie_fk FOREIGN KEY (id_vysetrenie)
        REFERENCES vysetrenie (id_vysetrenie),
    CONSTRAINT faktura_vysetrenie_uq UNIQUE (id_vysetrenie)
);

-- Uklada polozky faktury.
CREATE TABLE polozka_faktury (
    id_polozka_faktury NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_faktura         NUMBER NOT NULL,
    nazov              VARCHAR2(100) NOT NULL,
    mnozstvo           NUMBER(8,2),
    jednotkova_cena    NUMBER(10,2),
    sadzba_dph         NUMBER(5,2),
    CONSTRAINT polozka_faktury_pk PRIMARY KEY (id_polozka_faktury),
    CONSTRAINT polozka_faktury_faktura_fk FOREIGN KEY (id_faktura)
        REFERENCES faktura (id_faktura)
);

-- Eviduje jednotlive platby priradene k fakture.
CREATE TABLE platba (
    id_platba         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_faktura        NUMBER NOT NULL,
    datum_cas_platby  TIMESTAMP NOT NULL,
    suma              NUMBER(10,2) NOT NULL,
    sposob_platby     VARCHAR2(30),
    variabilny_symbol VARCHAR2(30),
    CONSTRAINT platba_pk PRIMARY KEY (id_platba),
    CONSTRAINT platba_faktura_fk FOREIGN KEY (id_faktura)
        REFERENCES faktura (id_faktura)
);

-- Eviduje liekove predpisy vystavene pri vysetreni.
CREATE TABLE predpis (
    id_predpis    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_vysetrenie NUMBER NOT NULL,
    nazov_lieku   VARCHAR2(100) NOT NULL,
    datum_od      DATE,
    datum_do      DATE,
    poznamka      VARCHAR2(200),
    CONSTRAINT predpis_pk PRIMARY KEY (id_predpis),
    CONSTRAINT predpis_vysetrenie_fk FOREIGN KEY (id_vysetrenie)
        REFERENCES vysetrenie (id_vysetrenie)
);

-- Zrychluje vyhladavanie zvierat podla majitela.
CREATE INDEX zviera_majitel_ix
    ON zviera (id_majitel);

-- Podporuje hladanie vysetreni konkretnej karty podla datumu.
CREATE INDEX vysetrenie_karta_datum_ix
    ON vysetrenie (id_zdravotna_karta, datum_cas_vysetrenia);

-- Podporuje hladanie vysetreni veterinara podla datumu.
CREATE INDEX vysetrenie_vet_datum_ix
    ON vysetrenie (id_veterinar, datum_cas_vysetrenia);

-- Zrychluje hladanie faktur podla stavu uhrady a splatnosti.
CREATE INDEX faktura_stav_splatnost_ix
    ON faktura (stav_uhrady, datum_splatnosti);

-- Zrychluje nacitanie poloziek faktury.
CREATE INDEX polozka_faktura_ix
    ON polozka_faktury (id_faktura);

-- Zrychluje nacitanie platieb faktury.
CREATE INDEX platba_faktura_ix
    ON platba (id_faktura);

-- Podporuje vyhladavanie a reporty platieb podla datumu.
CREATE INDEX platba_datum_ix
    ON platba (datum_cas_platby);

-- Zrychluje nacitanie predpisov pre konkretne vysetrenie.
CREATE INDEX predpis_vysetrenie_ix
    ON predpis (id_vysetrenie);

